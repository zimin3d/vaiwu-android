#!/usr/bin/env python3
"""Generate the Vaiwu art set through an OpenAI-compatible images API.

The prompts come from ``art_prompts.py`` (the machine-readable twin of
``firmware/docs/ART_PROMPTS.md``). By default the tool

1. writes every prompt to ``tools/art/prompts/`` as copy-paste ready files, and
2. generates the raw PNGs into ``tools/art/out/`` (git-ignored), skipping
   files that already exist.

The raw images are large and still carry the flat magenta key background, so the
second step of the pipeline, ``slice_art.py``, turns them into the 96x128 /
96x96 transparent sprites the app ships.

The endpoint is ``POST <base-url>/v1/images/generations`` and is configured
through flags or environment variables, so any OpenAI-compatible server works
(OpenAI, Cloud.ru, a local proxy, ...)::

    export VAIWU_ART_API_KEY=sk-...
    python3 tools/art/gen_art.py                        # everything
    python3 tools/art/gen_art.py --characters aoi       # one character
    python3 tools/art/gen_art.py --no-generate          # prompt files only
    python3 tools/art/gen_art.py --list                 # what would be built

Only the standard library is used, so the tool runs anywhere Python 3.9+ does.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import sys
import time
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

import art_prompts  # noqa: E402  (needs the path tweak above)

REPO_ROOT = Path(__file__).resolve().parents[2]
#: Raw generations go next to the slicer's default ``--src``, never straight
#: into the shipped asset folder: the app and the gallery expect the sliced
#: 96x128 / 96x96 PNGs that ``slice_art.py`` writes there.
DEFAULT_OUT_DIR = REPO_ROOT / "tools" / "art" / "out"
DEFAULT_PROMPTS_DIR = Path(__file__).resolve().parent / "prompts"
DEFAULT_BASE_URL = "https://api.openai.com"
DEFAULT_MODEL = "gpt-image-1"
DEFAULT_RESPONSE_FORMAT = "b64_json"

#: Magic prefix of every PNG file, checked before anything is written to disk.
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"

API_KEY_ENV = ("VAIWU_ART_API_KEY", "OPENAI_API_KEY")
BASE_URL_ENV = ("VAIWU_ART_BASE_URL", "OPENAI_BASE_URL")
MODEL_ENV = ("VAIWU_ART_MODEL", "OPENAI_IMAGE_MODEL")


class ArtApiError(RuntimeError):
    """Raised when the images API rejects a request or returns nothing usable.

    ``transient`` marks the failures worth retrying: rate limits, server errors
    and network hiccups. A rejected key or a wrong base URL is not transient.
    """

    def __init__(self, message: str, *, status: Optional[int] = None, transient: bool = False):
        super().__init__(message)
        self.status = status
        self.transient = transient


def env_first(names: Sequence[str]) -> Optional[str]:
    for name in names:
        value = os.environ.get(name)
        if value:
            return value
    return None


# --- Prompt files ------------------------------------------------------------


def render_markdown(assets: Sequence[art_prompts.Asset]) -> str:
    lines = [
        "# Vaiwu art prompts",
        "",
        "Generated by `tools/art/gen_art.py` - do not edit by hand.",
        "Source of truth: `firmware/docs/ART_PROMPTS.md` (vaiwu repo) and",
        "`tools/art/art_prompts.py`.",
        "",
        "## Style anchor (appended to every prompt)",
        "",
        "```",
        art_prompts.STYLE_ANCHOR,
        "```",
        "",
        "## Negative prompt",
        "",
        "```",
        art_prompts.NEGATIVE_PROMPT,
        "```",
        "",
        "## Assets",
        "",
    ]
    current_character: Optional[str] = None
    for asset in assets:
        if asset.character and asset.character != current_character:
            current_character = asset.character
            lines += ["", f"### {current_character}", ""]
        target = asset.target
        lines += [
            f"#### {asset.name} ({target.width}x{target.height}, {target.aspect})",
            "",
            "```",
            asset.prompt,
            "```",
            "",
        ]
    if any(asset.monster for asset in assets):
        lines += ["", "### Monsters", ""]
        for asset in assets:
            if not asset.monster:
                continue
            target = asset.target
            lines += [
                f"#### {asset.name} ({target.width}x{target.height}, {target.aspect})",
                "",
                "```",
                asset.prompt,
                "```",
                "",
            ]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_asset_file(asset: art_prompts.Asset) -> str:
    target = asset.target
    return (
        f"# {asset.name} ({target.width}x{target.height}, {target.aspect})\n"
        f"# api size: {target.api_size}\n"
        "\n"
        f"{asset.prompt}\n"
        "\n"
        f"# negative: {art_prompts.NEGATIVE_PROMPT}\n"
    )


def write_prompt_files(assets: Sequence[art_prompts.Asset], out_dir: Path) -> None:
    """Write the prompt set as JSON, Markdown and per-subject text files."""
    out_dir.mkdir(parents=True, exist_ok=True)

    payload = {
        "style_anchor": art_prompts.STYLE_ANCHOR,
        "negative_prompt": art_prompts.NEGATIVE_PROMPT,
        "emotions": list(art_prompts.EMOTIONS),
        "assets": [
            {
                "name": asset.name,
                "kind": asset.kind,
                "filename": asset.filename,
                "character": asset.character,
                "emotion": asset.emotion,
                "monster": asset.monster,
                "prompt": asset.prompt,
                "final_size": [asset.target.width, asset.target.height],
                "aspect": asset.target.aspect,
                "api_size": asset.target.api_size,
            }
            for asset in assets
        ],
    }
    (out_dir / "prompts.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    (out_dir / "prompts.md").write_text(render_markdown(assets), encoding="utf-8")

    groups: Dict[str, List[art_prompts.Asset]] = {}
    for asset in assets:
        if asset.character:
            groups.setdefault(f"characters/{asset.character}", []).append(asset)
        elif asset.monster:
            groups.setdefault(f"monsters/{asset.monster}", []).append(asset)
    for relative, group in groups.items():
        path = out_dir / f"{relative}.txt"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            "\n".join(render_asset_file(asset) for asset in group), encoding="utf-8"
        )


# --- Images API --------------------------------------------------------------


@dataclass
class ApiConfig:
    base_url: str = DEFAULT_BASE_URL
    api_key: str = ""
    model: str = DEFAULT_MODEL
    response_format: str = DEFAULT_RESPONSE_FORMAT
    timeout: float = 120.0
    size_override: Optional[str] = None
    retries: int = 2
    retry_delay: float = 2.0

    @property
    def endpoint(self) -> str:
        # Providers document their base URL either with or without the /v1
        # suffix, so accept both instead of producing /v1/v1/... and a 404.
        base = self.base_url.rstrip("/")
        if base.endswith("/v1"):
            base = base[: -len("/v1")]
        return base + "/v1/images/generations"

    def size_for(self, asset: art_prompts.Asset) -> str:
        return self.size_override or asset.target.api_size


def post_json(url: str, payload: dict, api_key: str, timeout: float) -> dict:
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=body,
        method="POST",
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}",
            "User-Agent": "vaiwu-art/1.0",
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            content_type = response.headers.get("Content-Type", "")
            raw = response.read()
    except urllib.error.HTTPError as error:
        # HTTPError is also a file-like response, so it must be closed; leaving
        # it to the garbage collector leaks the connection and warns.
        try:
            detail = error.read().decode("utf-8", errors="replace")
        finally:
            error.close()
        try:
            parsed = json.loads(detail)
        except json.JSONDecodeError:
            parsed = {}
        message = parsed.get("error", {}).get("message") if isinstance(parsed, dict) else None
        raise ArtApiError(
            f"HTTP {error.code}: {message or detail.strip()[:400]}",
            status=error.code,
            transient=error.code == 429 or error.code >= 500,
        ) from error
    except urllib.error.URLError as error:
        raise ArtApiError(f"connection failed: {error.reason}", transient=True) from error

    try:
        return json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        # A relay that serves its web UI on the apex domain answers every path
        # with the same HTML page and a 200, which is otherwise baffling.
        hint = ""
        if "html" in content_type.lower() or raw.lstrip()[:1] == b"<":
            hint = (
                " - the response is HTML, so this host serves a web UI rather than"
                " the API; check the base URL"
            )
        raise ArtApiError(f"malformed JSON response: {error}{hint}") from error


def extract_image(data: dict, timeout: float) -> bytes:
    entries = data.get("data")
    if not isinstance(entries, list) or not entries:
        raise ArtApiError(f"response has no image data: {json.dumps(data)[:400]}")
    entry = entries[0]
    encoded = entry.get("b64_json")
    if encoded:
        return base64.b64decode(encoded)
    url = entry.get("url")
    if url:
        request = urllib.request.Request(
            url, headers={"User-Agent": "vaiwu-art/1.0"}
        )
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            error.close()
            raise ArtApiError(
                f"could not download image from {url}: {error}", transient=True
            ) from error
        except urllib.error.URLError as error:
            raise ArtApiError(
                f"could not download image from {url}: {error}", transient=True
            ) from error
    raise ArtApiError(f"image entry has neither b64_json nor url: {json.dumps(entry)[:400]}")


def sniff_format(image: bytes) -> str:
    """Name the image format of *image* from its magic bytes."""
    if image[:8] == PNG_SIGNATURE:
        return "PNG"
    if image[:4] == b"RIFF" and image[8:12] == b"WEBP":
        return "WebP"
    for name, magic in (
        ("JPEG", b"\xff\xd8\xff"),
        ("GIF", b"GIF8"),
        ("BMP", b"BM"),
        ("TIFF", b"II*\x00"),
        ("TIFF", b"MM\x00*"),
    ):
        if image[: len(magic)] == magic:
            return name
    if image.lstrip()[:1] == b"<":
        return "HTML"
    return "unknown"


def require_png(image: bytes) -> bytes:
    """Return *image* when it really is a PNG, otherwise fail without retrying.

    A relay answered one request with a WebP and it was written to a ``.png``
    name, only blowing up later in the slicer; checking the format here keeps
    the error next to the asset that produced it, and a provider that always
    sends the wrong format is not transient, so it is not retried either.
    """
    if image[:8] != PNG_SIGNATURE:
        raise ArtApiError(
            f"image is {sniff_format(image)}, not PNG - refusing to write it as .png"
        )
    return image


def generate_image(config: ApiConfig, prompt: str, size: str) -> bytes:
    """Generate one image, retrying the failures that are worth retrying."""
    attempt = 0
    while True:
        try:
            return _generate_once(config, prompt, size)
        except ArtApiError as error:
            if not error.transient or attempt >= config.retries:
                raise
            delay = config.retry_delay * (2 ** attempt)
            attempt += 1
            print(f"    transient failure ({error}), retry {attempt}/{config.retries} in {delay:.0f}s")
            time.sleep(delay)


def _generate_once(config: ApiConfig, prompt: str, size: str) -> bytes:
    payload = {"model": config.model, "prompt": prompt, "n": 1, "size": size}
    if config.response_format and config.response_format != "none":
        payload["response_format"] = config.response_format
    try:
        data = post_json(config.endpoint, payload, config.api_key, config.timeout)
    except ArtApiError as error:
        # gpt-image-1 always returns base64 and rejects response_format outright.
        if "response_format" not in payload or "response_format" not in str(error):
            raise
        payload.pop("response_format")
        data = post_json(config.endpoint, payload, config.api_key, config.timeout)
    return require_png(extract_image(data, config.timeout))


# --- CLI ---------------------------------------------------------------------


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate the Vaiwu art set with an OpenAI-compatible images API.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--base-url",
        default=env_first(BASE_URL_ENV) or DEFAULT_BASE_URL,
        help=f"API root, with or without a trailing /v1 (env: {', '.join(BASE_URL_ENV)})",
    )
    parser.add_argument(
        "--api-key",
        default=env_first(API_KEY_ENV) or "",
        help=f"bearer token (env: {', '.join(API_KEY_ENV)})",
    )
    parser.add_argument(
        "--model",
        default=env_first(MODEL_ENV) or DEFAULT_MODEL,
        help=f"image model name (env: {', '.join(MODEL_ENV)})",
    )
    parser.add_argument(
        "--size",
        default=None,
        help="override the API size for every asset, e.g. 1024x1024",
    )
    parser.add_argument(
        "--response-format",
        default=DEFAULT_RESPONSE_FORMAT,
        choices=("b64_json", "url", "none"),
        help="'none' omits the field entirely",
    )
    parser.add_argument(
        "--timeout",
        type=float,
        default=120.0,
        help="per-request timeout in seconds",
    )
    parser.add_argument(
        "--retries",
        type=int,
        default=2,
        help="extra attempts per asset after a rate limit, server error or "
        "network failure",
    )
    parser.add_argument(
        "--retry-delay",
        type=float,
        default=2.0,
        help="seconds before the first retry; the delay doubles after that",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=DEFAULT_OUT_DIR,
        help="folder for the generated PNGs",
    )
    parser.add_argument(
        "--prompts-out",
        type=Path,
        default=DEFAULT_PROMPTS_DIR,
        help="folder for the prompt files",
    )
    parser.add_argument(
        "--characters",
        nargs="+",
        choices=tuple(art_prompts.CHARACTERS),
        help="only these characters (default: all)",
    )
    parser.add_argument(
        "--emotions",
        nargs="+",
        choices=art_prompts.EMOTIONS,
        help="only these emotions (default: all)",
    )
    parser.add_argument(
        "--monsters",
        nargs="+",
        choices=tuple(art_prompts.MONSTERS),
        help="only these monsters (default: all)",
    )
    parser.add_argument(
        "--assets",
        nargs="+",
        metavar="NAME",
        help="only these asset names, e.g. sprite_aoi_idle monster_slime "
        "(cannot be combined with the other selectors; see --list)",
    )
    parser.add_argument(
        "--no-prompts",
        action="store_true",
        help="do not write the prompt files",
    )
    parser.add_argument(
        "--no-generate",
        action="store_true",
        help="only write the prompt files, never touch the network",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="regenerate PNGs that already exist",
    )
    parser.add_argument(
        "--list",
        action="store_true",
        help="print the asset list and exit",
    )
    return parser


def select_assets(args) -> List[art_prompts.Asset]:
    """Resolve the CLI selectors into an asset list."""
    others = {
        "--characters": args.characters,
        "--emotions": args.emotions,
        "--monsters": args.monsters,
    }
    if args.assets:
        clashing = [name for name, value in others.items() if value]
        if clashing:
            raise ValueError(
                f"--assets cannot be combined with {', '.join(clashing)}"
            )
        assets = art_prompts.build_assets()
        by_name = {asset.name: asset for asset in assets}
        unknown = [name for name in args.assets if name not in by_name]
        if unknown:
            raise ValueError(
                "unknown asset(s): "
                + ", ".join(unknown)
                + " - run with --list to see the names"
            )
        return [by_name[name] for name in args.assets]

    return art_prompts.build_assets(
        characters=args.characters,
        emotions=args.emotions,
        monsters=args.monsters,
    )


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)

    try:
        assets = select_assets(args)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.list:
        for asset in assets:
            print(f"{asset.filename:<32} {asset.target.api_size:<10} {asset.prompt[:60]}...")
        print(f"{len(assets)} assets")
        return 0

    if not args.no_prompts:
        write_prompt_files(assets, args.prompts_out)
        print(f"wrote {len(assets)} prompts to {args.prompts_out}")

    if args.no_generate:
        return 0

    if not args.api_key:
        print(
            "error: no API key. Set " + " or ".join(API_KEY_ENV) + ", pass --api-key,",
            file=sys.stderr,
        )
        print("       or use --no-generate to only write the prompt files.", file=sys.stderr)
        return 2

    config = ApiConfig(
        base_url=args.base_url,
        api_key=args.api_key,
        model=args.model,
        response_format=args.response_format,
        timeout=args.timeout,
        size_override=args.size,
        retries=args.retries,
        retry_delay=args.retry_delay,
    )
    args.out_dir.mkdir(parents=True, exist_ok=True)

    failures: List[str] = []
    generated = 0
    for index, asset in enumerate(assets, start=1):
        destination = args.out_dir / asset.filename
        if destination.exists() and not args.force:
            print(f"[{index}/{len(assets)}] {asset.filename}: exists, skipping")
            continue
        try:
            image = generate_image(config, asset.prompt, config.size_for(asset))
        except ArtApiError as error:
            failures.append(asset.filename)
            print(f"[{index}/{len(assets)}] {asset.filename}: FAILED ({error})", file=sys.stderr)
            continue
        destination.write_bytes(image)
        generated += 1
        print(f"[{index}/{len(assets)}] {asset.filename}: {len(image)} bytes")

    print(f"generated {generated}, skipped {len(assets) - generated - len(failures)}, failed {len(failures)}")
    if failures:
        print("failed assets: " + ", ".join(failures), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
